import { describe, it, expect } from 'vitest';
import type { SDKSessionInfo, SessionMessage } from '@anthropic-ai/claude-agent-sdk';
import { toSessionCards, toRestoredMessages, parseGitStatus, toProjects } from '../sessions';

const info = (over: Partial<SDKSessionInfo>): SDKSessionInfo => ({
  sessionId: 's', summary: 'A summary', lastModified: 0, cwd: '/home/deck/proj', ...over,
});

describe('toSessionCards', () => {
  it('lists newest first, prefers the custom title, and names the project folder', () => {
    const cards = toSessionCards([
      info({ sessionId: 'old', lastModified: 1, summary: 'Old work' }),
      info({ sessionId: 'new', lastModified: 2, customTitle: 'Racer polish', gitBranch: 'main' }),
    ], () => true);
    expect(cards.map((c) => c.id)).toEqual(['new', 'old']);
    expect(cards[0]).toMatchObject({ title: 'Racer polish', project: 'proj', branch: 'main' });
    expect(cards[1].branch).toBeNull();
  });

  it('leaves out sessions that can\'t be resumed here', () => {
    const cards = toSessionCards([
      info({ sessionId: 'gone', cwd: '/home/deck/deleted' }),
      info({ sessionId: 'nocwd', cwd: undefined }),
      info({ sessionId: 'ok' }),
    ], (d) => d === '/home/deck/proj');
    expect(cards.map((c) => c.id)).toEqual(['ok']);
  });

  it('shows no branch where Claude Code only recorded HEAD', () => {
    const [c] = toSessionCards([info({ gitBranch: 'HEAD' })], () => true);
    expect(c.branch).toBeNull();
  });

  it('keeps titles to one short line', () => {
    const [c] = toSessionCards([info({ summary: `fix\n\n${'x'.repeat(300)}` })], () => true);
    expect(c.title).not.toContain('\n');
    expect(c.title.length).toBeLessThanOrEqual(90);
  });
});

const msg = (type: SessionMessage['type'], uuid: string, content: unknown, parent: string | null = null): SessionMessage => ({
  type, uuid, session_id: 's', message: { content }, parent_tool_use_id: parent, parent_agent_id: null,
});

describe('toRestoredMessages', () => {
  it('keeps the pilot\'s prompts and Claude\'s replies, one bubble per turn, anchored to its last message', () => {
    const out = toRestoredMessages([
      msg('user', 'u1', 'Implement add in todos.js'),
      msg('assistant', 'a1', [{ type: 'text', text: 'Looking at the file.' }]),
      msg('assistant', 'a2', [{ type: 'tool_use', name: 'Edit' }]),
      msg('user', 't1', [{ type: 'tool_result', content: 'ok' }]),
      msg('assistant', 'a3', [{ type: 'text', text: 'Done. Tests pass.\n<confidence>high</confidence>' }]),
      msg('user', 'u2', 'Now commit'),
    ], 0);
    expect(out.map((m) => [m.role, m.content, m.anchor ?? null])).toEqual([
      ['user', 'Implement add in todos.js', null],
      ['assistant', 'Looking at the file.\n\nDone. Tests pass.', 'a3'],
      ['user', 'Now commit', null],
    ]);
  });

  it('drops Claude Code\'s own bookkeeping and subagent traffic', () => {
    const out = toRestoredMessages([
      msg('user', 'c1', '<command-name>/compact</command-name>'),
      msg('user', 'c2', 'Caveat: The messages below were generated by the user while running local commands.'),
      msg('assistant', 'sub', [{ type: 'text', text: 'subagent says hi' }], 'toolu_1'),
      msg('user', 'u1', [{ type: 'text', text: 'Real question' }]),
    ], 0);
    expect(out.map((m) => m.content)).toEqual(['Real question']);
  });
});

describe('parseGitStatus', () => {
  it('reads branch, ahead/behind and the count of changed files', () => {
    expect(parseGitStatus('## main...origin/main [ahead 2, behind 1]\n M src/a.ts\n?? new.txt\n'))
      .toEqual({ branch: 'main', ahead: 2, behind: 1, changes: 2 });
  });

  it('handles a branch with no upstream, a fresh repo and a detached HEAD', () => {
    expect(parseGitStatus('## feat/x')).toEqual({ branch: 'feat/x', ahead: 0, behind: 0, changes: 0 });
    expect(parseGitStatus('## No commits yet on main\n?? a')).toMatchObject({ branch: 'main', changes: 1 });
    expect(parseGitStatus('## HEAD (no branch)').branch).toBeNull();
  });
});

describe('toProjects', () => {
  it('groups stints by folder, newest project first, with its git state', () => {
    const cards = toSessionCards([
      info({ sessionId: 'a1', cwd: '/w/alpha', lastModified: 1 }),
      info({ sessionId: 'b1', cwd: '/w/beta', lastModified: 3 }),
      info({ sessionId: 'a2', cwd: '/w/alpha', lastModified: 2 }),
    ], () => true);
    const projects = toProjects(cards, { '/w/beta': { branch: 'main', ahead: 0, behind: 0, changes: 4 } });
    expect(projects.map((p) => [p.name, p.sessions.map((s) => s.id)])).toEqual([
      ['beta', ['b1']],
      ['alpha', ['a2', 'a1']],
    ]);
    expect(projects[0].git?.changes).toBe(4);
    expect(projects[1].git).toBeNull();
  });
});
